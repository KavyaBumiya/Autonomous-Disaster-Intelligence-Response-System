import uuid
from datetime import datetime
from sqlalchemy import String, Float, Integer, DateTime, Text, ForeignKey, Boolean, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.core.database import Base


class Incident(Base):
    __tablename__ = "incidents"

    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=lambda: str(uuid.uuid4())
    )
    zone_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("zones.id"), nullable=False
    )

    # ── Classification ────────────────────────────────────────────────────
    disaster_type: Mapped[str | None]  = mapped_column(String(50), nullable=True)
    severity_score: Mapped[float]      = mapped_column(Float, default=0.0)
    priority_score: Mapped[float]      = mapped_column(Float, default=0.0)
    priority_band: Mapped[str | None]  = mapped_column(String(20), nullable=True,
                                                        default="LOW")
    confidence: Mapped[float]          = mapped_column(Float, default=0.0)

    # ── XAI (from Decision Engine) ────────────────────────────────────────
    xai_reasoning: Mapped[str | None]  = mapped_column(Text, nullable=True)

    # ── AI-generated human-readable fields ─────────────────────────────
    # These are generated by the LLM *from* the engine evidence — never used
    # as inputs to the deterministic score.
    groq_summary: Mapped[str | None]      = mapped_column(Text, nullable=True)
    groq_explanation: Mapped[str | None]  = mapped_column(Text, nullable=True)

    # ── Status ────────────────────────────────────────────────────────────
    status: Mapped[str]  = mapped_column(String(30), default="active")
    # active | resolved | false_alarm
    active: Mapped[bool] = mapped_column(Boolean, default=True)

    # ── Aggregate signals ─────────────────────────────────────────────────
    report_count: Mapped[int]       = mapped_column(Integer, default=0)
    avg_trust_score: Mapped[float]  = mapped_column(Float, default=0.0)

    # ── Victim detection (from CV agent) ─────────────────────────────────
    victim_count: Mapped[int]           = mapped_column(Integer, default=0)
    victim_confidence: Mapped[float]    = mapped_column(Float, default=0.0)

    # ── Timestamps ────────────────────────────────────────────────────────
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
    # polled_at: last time a poller touched this incident (added migration 0003)
    polled_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # ── Relationships ─────────────────────────────────────────────────────
    zone:         Mapped["Zone"]              = relationship("Zone",        back_populates="incidents")
    agent_outputs: Mapped[list["AgentOutput"]] = relationship("AgentOutput", back_populates="incident", lazy="select")
    actions:       Mapped[list["Action"]]      = relationship("Action",      back_populates="incident", lazy="select")
